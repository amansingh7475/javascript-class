let ch = parseInt(prompt("1:\n2:\n3:\n4:\n5:\n6:\n7:"));
    switch (ch) {
        case 1:
            console.log("%d Is Monday",ch);
            break;

        case 2:
            console.log("%d Is Tuesday",ch);
            break;

        case 3:
            console.log("%d Is Wednesday",ch);
            break;

        case 4:
            console.log("%d Is Thursday",ch);
            break;

        case 5:
            console.log("%d Is Friday",ch);
            break;

        case 6:
            console.log("%d Is saturday",ch);
            break;

        case 7:
            console.log("%d Is sunday",ch);
            break;

        default:
            console.log("Invalid number")
            break;
    }
